CREATE TABLE reservas (
    id_reserva          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario          INTEGER NOT NULL REFERENCES usuarios (id_usuario),
    id_negocio          INTEGER NOT NULL REFERENCES negocios (id_negocio),
    id_servicio         INTEGER NOT NULL REFERENCES servicios (id_servicio),
    fecha_reserva       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_inicio        DATE NOT NULL,
    fecha_fin           DATE NOT NULL,
    cantidad_personas   INTEGER NOT NULL DEFAULT 1,
    cantidad_servicio   INTEGER NOT NULL DEFAULT 1,
    metodo_pago         VARCHAR(50) NOT NULL,
    precio_unitario     NUMERIC(12,2) NOT NULL DEFAULT 0,
    precio_total        NUMERIC(12,2) NOT NULL DEFAULT 0,
    valor_total         NUMERIC(12,2) NOT NULL DEFAULT 0,
    abono               NUMERIC(12,2) NOT NULL DEFAULT 0,
    saldo_pendiente     NUMERIC(12,2) NOT NULL DEFAULT 0,
    estado              VARCHAR(30) NOT NULL DEFAULT 'Pendiente',
    observaciones       TEXT,
    CHECK (fecha_fin >= fecha_inicio)
);

-- Cálculo automático del precio, total y saldo (reemplaza los 2 triggers de MariaDB)
CREATE OR REPLACE FUNCTION calcular_reserva()
RETURNS TRIGGER AS $$
BEGIN
    SELECT precio INTO NEW.precio_unitario
    FROM servicios
    WHERE id_servicio = NEW.id_servicio
    LIMIT 1;

    NEW.valor_total     := NEW.precio_unitario * NEW.cantidad_servicio;
    NEW.precio_total    := NEW.valor_total;
    NEW.saldo_pendiente := NEW.valor_total - NEW.abono;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER calcular_reserva_insert
    BEFORE INSERT ON reservas
    FOR EACH ROW EXECUTE FUNCTION calcular_reserva();

CREATE TRIGGER calcular_reserva_update
    BEFORE UPDATE ON reservas
    FOR EACH ROW EXECUTE FUNCTION calcular_reserva();

CREATE TABLE favoritos (
    id_favorito  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario   INTEGER NOT NULL REFERENCES usuarios (id_usuario) ON DELETE CASCADE,
    id_negocio   INTEGER NOT NULL REFERENCES negocios (id_negocio) ON DELETE CASCADE,
    fecha        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_usuario, id_negocio)
);

CREATE TABLE comentarios (
    id_comentario  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario     INTEGER NOT NULL REFERENCES usuarios (id_usuario),
    id_negocio     INTEGER NOT NULL REFERENCES negocios (id_negocio),
    calificacion   INTEGER CHECK (calificacion BETWEEN 1 AND 5),
    comentario     TEXT,
    fecha          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    utiliza        BOOLEAN NOT NULL DEFAULT FALSE
);

-- =====================================================================
-- 5. PARTE DEL ADMINISTRADOR (pagos, facturas)
-- =====================================================================

CREATE TABLE pagos (
    id_pago         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva      INTEGER NOT NULL REFERENCES reservas (id_reserva),
    id_metodo_pago  INTEGER NOT NULL REFERENCES metodos_pago (id_metodo_pago),
    valor           NUMERIC(12,2) NOT NULL,
    referencia      VARCHAR(100),
    estado          VARCHAR(30) NOT NULL DEFAULT 'Pendiente',
    fecha_pago      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    observaciones   TEXT
);

CREATE TABLE facturas (
    id_factura     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva     INTEGER NOT NULL REFERENCES reservas (id_reserva),
    monto_factura  NUMERIC(12,2) NOT NULL DEFAULT 0,
    fecha_emision  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    subtotal       NUMERIC(12,2) NOT NULL DEFAULT 0,
    impuestos      NUMERIC(12,2) NOT NULL DEFAULT 0,
    total          NUMERIC(12,2) NOT NULL DEFAULT 0,
    estado         VARCHAR(30) NOT NULL DEFAULT 'Emitida'
);

